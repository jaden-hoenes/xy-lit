// Generates src/styles/generated/{default,base}.css.ts from the vendored xyflow CSS
// (spec/10-styles-theming.md §CSS pipeline). Output is committed and byte-stable: the CSS goes
// through the repo's Prettier config, so `pnpm build` (which runs this) never dirties the tree.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import { format, resolveConfig } from 'prettier';
import nested from 'postcss-nested';
// postcss-rename ships CommonJS only
const rename = createRequire(import.meta.url)('postcss-rename');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendor = join(root, 'src/styles/vendor');
const out = join(root, 'src/styles/generated');

const bundles = {
  // React's style.css
  default: ['init.css', 'style.css', 'node-resizer.css'],
  // React's base.css
  base: ['init.css', 'base.css', 'node-resizer.css'],
};

const escapeTemplate = (css) =>
  css.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const processor = postcss([
  nested(),
  rename({ strategy: (name) => name.replace(/^xy-flow/, 'lit-flow') }),
]);

const prettierOptions = { ...(await resolveConfig(join(out, 'x.css'))), parser: 'css' };

mkdirSync(out, { recursive: true });
for (const [name, files] of Object.entries(bundles)) {
  const input = files.map((f) => readFileSync(join(vendor, f), 'utf8')).join('\n');
  const processed = await processor.process(input, { from: undefined });
  const css = (await format(processed.css, prettierOptions)).trimEnd() + '\n';
  const text = `// generated by scripts/gen-styles.mjs from xyflow@3d35b57 (MIT). Do not edit.
import { unsafeCSS } from 'lit';
export default unsafeCSS(\`${escapeTemplate(css)}\`);
`;
  const file = join(out, `${name}.css.ts`);
  // Leave an identical file alone: rewriting it moves its mtime, and a dev server or test run that
  // is watching it reloads the page (a `pnpm build` while `pnpm e2e` runs failed every open test).
  const same = existsSync(file) && readFileSync(file, 'utf8') === text;
  if (!same) writeFileSync(file, text);
  console.log(`gen-styles: ${same ? 'unchanged' : 'wrote'} ${name}.css.ts (${css.length} bytes)`);
}
